// Generates src/server/content/pages.generated.ts: a static import for every career page JSON in
// packages/content/careers/pages (the bundler cannot glob a directory). Run by predev/prebuild/etc.;
// a test fails when the committed file is stale.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pagesDir = join(here, '../../../packages/content/careers/pages');
const out = join(here, '../src/server/content/pages.generated.ts');

const ids = readdirSync(pagesDir)
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.replace(/\.json$/, ''))
  .sort();

const ident = (id) => `p_${id.replace(/[^a-zA-Z0-9]/g, '_')}`;
const body = [
  '// GENERATED by scripts/gen-career-pages.mjs. Do not edit.',
  ...ids.map((id) => `import ${ident(id)} from '../../../../../packages/content/careers/pages/${id}.json';`),
  '',
  'export const RAW_CAREER_PAGES: Record<string, unknown> = {',
  ...ids.map((id) => `  ${JSON.stringify(id)}: ${ident(id)},`),
  '};',
  '',
].join('\n');

let current = '';
try {
  current = readFileSync(out, 'utf8');
} catch {
  /* first run */
}
if (current !== body) writeFileSync(out, body);
